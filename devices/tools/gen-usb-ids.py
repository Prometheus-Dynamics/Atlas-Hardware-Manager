#!/usr/bin/env python3
"""Render the USB ids Atlas matches into the files that carry them.

Reads devices/usb-ids.json (the download modes and the Pi's storage gadget)
and devices/ecosystem.json (the board gadget and the flasher). Writes the
Linux udev rules (crates/atlas-usb-ids/generated/ and the packaged copy) and
the Windows installer's WinUSB binds (the generated region of hooks.nsh).
The Rust table in crates/atlas-usb-ids/src/lib.rs is not generated: a test in
crates/atlas-devices/tests/usb_ids.rs checks it against the same data.

    devices/tools/gen-usb-ids.py --check   print a diff and exit 1 instead of writing
"""

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDS = ROOT / "devices" / "usb-ids.json"
ECOSYSTEM = ROOT / "devices" / "ecosystem.json"
RULES = [
    ROOT / "crates" / "atlas-usb-ids" / "generated" / "60-atlas-usbboot.rules",
    ROOT / "apps" / "desktop" / "src-tauri" / "bundle" / "linux" / "60-atlas-usbboot.rules",
]
HOOKS = ROOT / "apps" / "desktop" / "src-tauri" / "bundle" / "windows" / "hooks.nsh"
TOOL = "devices/tools/gen-usb-ids.py"
BEGIN = "  ; BEGIN generated by devices/tools/gen-usb-ids.py (do not edit)"
END = "  ; END generated"


class GenError(Exception):
    pass


def hex4(value: str) -> str:
    """A four-digit lowercase hex id from the data, checked."""
    text = value.lower()
    if len(text) != 4 or any(c not in "0123456789abcdef" for c in text):
        raise GenError(f"not a USB id: {value!r}")
    return text


def load() -> tuple[dict, dict]:
    ids = json.loads(IDS.read_text())
    eco = json.loads(ECOSYSTEM.read_text())
    if ids.get("schema") != "urn:board:usb-ids:1":
        raise GenError(f"{IDS}: schema must be urn:board:usb-ids:1")
    if eco.get("schema") != "urn:board:ecosystem:1":
        raise GenError(f"{ECOSYSTEM}: schema must be urn:board:ecosystem:1")
    modes = ids["boot_modes"]
    seen = set()
    for mode in modes:
        key = (hex4(mode["vid"]), hex4(mode["pid"]))
        if key in seen:
            raise GenError(f"{IDS}: {key[0]}:{key[1]} is listed twice")
        seen.add(key)
    wide = {hex4(v) for v in ids.get("vendor_wide", [])}
    for vid in wide:
        if not any(hex4(m["vid"]) == vid for m in modes):
            raise GenError(f"{IDS}: vendor_wide {vid} has no boot mode")
    return ids, eco


def rules_text(ids: dict, eco: dict) -> str:
    modes = ids["boot_modes"]
    wide = {hex4(v) for v in ids.get("vendor_wide", [])}
    gadget = eco["identity"]["usb_gadget"]
    flasher = eco["flasher"]["product"]
    board_vid, board_pid = hex4(gadget["vid"]), hex4(gadget["pid"])
    manufacturer = gadget["manufacturer"]
    storage = ids["storage_gadget"]
    storage_vid, storage_pid = hex4(storage["vid"]), hex4(storage["pid"])

    lines = [
        "# Installed by Atlas Hardware Manager. Generated by",
        f"# {TOOL} from devices/usb-ids.json and devices/ecosystem.json;",
        "# change those and run the tool, do not edit this file.",
    ]

    # Each vendor's download modes, in the order the table lists them.
    vendors: dict[str, list[dict]] = {}
    for mode in modes:
        vendors.setdefault(hex4(mode["vid"]), []).append(mode)
    for vid, group in vendors.items():
        names = "; ".join(dict.fromkeys(m["name"] for m in group))
        lines.append(f"# USB download modes Atlas flashes from: {names}.")
        if vid in wide:
            lines.append(
                f'SUBSYSTEM=="usb", ATTR{{idVendor}}=="{vid}", MODE="0660", TAG+="uaccess"'
            )
        else:
            pids = "|".join(hex4(m["pid"]) for m in group)
            lines.append(
                f'SUBSYSTEM=="usb", ATTR{{idVendor}}=="{vid}", ATTR{{idProduct}}=="{pids}", '
                'MODE="0660", TAG+="uaccess"'
            )

    lines += [
        "# The mass-storage gadget's serial console, so Atlas can restart a board",
        "# into its new image after a flash.",
        f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{storage_vid}", '
        f'ATTRS{{idProduct}}=="{storage_pid}", TAG+="uaccess"',
        "# Atlas's flasher: its console and its bulk interface, by product name,",
        f"# since {board_vid}:{board_pid} alone is any Linux gadget (a running board's own console among them).",
        f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{board_vid}", ATTRS{{idProduct}}=="{board_pid}", '
        f'ATTRS{{product}}=="{flasher}", TAG+="uaccess"',
        f'SUBSYSTEM=="usb", ATTR{{idVendor}}=="{board_vid}", ATTR{{idProduct}}=="{board_pid}", '
        f'ATTR{{product}}=="{flasher}", MODE="0660", TAG+="uaccess"',
        "# A running board's own console, by its manufacturer: Atlas manages a board",
        "# plugged in here through it, with no SSH key (holding the cable is the access).",
        f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{board_vid}", ATTRS{{idProduct}}=="{board_pid}", '
        f'ATTRS{{manufacturer}}=="{manufacturer}", TAG+="uaccess"',
    ]
    return "\n".join(lines) + "\n"


def hooks_text(ids: dict, current: str) -> str:
    binds = []
    for mode in ids["boot_modes"]:
        vid, pid = hex4(mode["vid"]), hex4(mode["pid"])
        binds.append(f'  !insertmacro ATLAS_BIND_WINUSB "{mode["name"]}" 0x{vid} 0x{pid}')
    body = "\n".join(binds)
    start = current.find(BEGIN)
    end = current.find(END)
    if start < 0 or end < 0 or end < start:
        raise GenError(f"{HOOKS}: no generated region (BEGIN/END markers)")
    start_line_end = current.index("\n", start) + 1
    return current[:start_line_end] + body + "\n" + current[end:]


def outputs(ids: dict, eco: dict) -> dict[Path, str]:
    rules = rules_text(ids, eco)
    files = {path: rules for path in RULES}
    files[HOOKS] = hooks_text(ids, HOOKS.read_text())
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="print a diff and exit 1 instead of writing")
    args = parser.parse_args()

    try:
        ids, eco = load()
        files = outputs(ids, eco)
    except (GenError, KeyError, ValueError) as error:
        print(f"gen-usb-ids: {error}", file=sys.stderr)
        return 1

    stale = []
    for path, text in files.items():
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        stale.append(path)
        rel = str(path.relative_to(ROOT))
        if args.check:
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(True), text.splitlines(True), f"a/{rel}", f"b/{rel} (from the data)"
                )
            )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"gen-usb-ids: wrote {rel}")

    if args.check and stale:
        print(
            f"gen-usb-ids: {len(stale)} file(s) disagree with devices/usb-ids.json; run {TOOL} and commit the result",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
